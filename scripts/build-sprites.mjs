// Converts the spritesheetgen JSON descriptors into plain ES modules.
//
// The source JSONs always carry `"image": "spritesheet.png"`, which is wrong
// for this project (each sheet has its own file next to it). The generated
// modules point at the real PNG with a URL relative to the module itself, so
// they resolve no matter where the page is served from.
//
//   node scripts/build-sprites.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SPRITES_DIR = path.join(ROOT, 'sprites');
const OUT_DIR = path.join(ROOT, 'js', 'sprites');

const BANNER = '// AUTO-GENERATED by scripts/build-sprites.mjs - do not edit by hand.';

// "frame_007" -> 7. Anything without a trailing number sorts last.
function frameIndex(key) {
  const match = /(\d+)\s*$/.exec(String(key));
  return match ? Number(match[1]) : Number.MAX_SAFE_INTEGER;
}

export function convertSheet(name, json) {
  const entries = Object.entries(json?.frames ?? {});
  entries.sort((a, b) => frameIndex(a[0]) - frameIndex(b[0]));

  const frames = [];
  for (const [key, frame] of entries) {
    if (frame?.rotated) {
      throw new Error(
        `${name}: frame ${key} is rotated; the renderer only draws upright frames`,
      );
    }
    const { x = 0, y = 0, w = 0, h = 0 } = frame?.frame ?? {};
    frames.push({ x, y, w, h });
  }

  return {
    name,
    image: `../../sprites/${name}.png`,
    frames,
    size: { w: json?.meta?.size?.w ?? 0, h: json?.meta?.size?.h ?? 0 },
  };
}

export function renderModule(name, data) {
  const frames = data.frames.map((f) => `  { x: ${f.x}, y: ${f.y}, w: ${f.w}, h: ${f.h} },`);
  return [
    BANNER,
    `export const name = ${JSON.stringify(name)};`,
    `export const image = new URL(${JSON.stringify(data.image)}, import.meta.url).href;`,
    'export const frames = [',
    frames.join('\n'),
    '];',
    `export const size = { w: ${data.size.w}, h: ${data.size.h} };`,
    '',
  ].join('\n');
}

export function listSheets(dir = SPRITES_DIR) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((file) => file.endsWith('.json'))
    .map((file) => file.slice(0, -'.json'.length))
    .sort();
}

function renderIndex(names) {
  const imports = names.map((name) => `import * as ${ident(name)} from './${name}.js';`);
  const entries = names.map((name) => `  ${JSON.stringify(name)}: ${ident(name)},`);
  return [
    BANNER,
    ...imports,
    'export const SHEETS = {',
    entries.join('\n'),
    '};',
    '',
  ].join('\n');
}

// "mario-talk" -> "marioTalk"
function ident(name) {
  return name.replace(/[^a-zA-Z0-9]+(.)/g, (_, chr) => chr.toUpperCase()).replace(/^./, (c) => c.toLowerCase());
}

export function buildAll() {
  const names = listSheets();
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const written = [];
  for (const name of names) {
    const json = JSON.parse(fs.readFileSync(path.join(SPRITES_DIR, `${name}.json`), 'utf8'));
    const data = convertSheet(name, json);
    const target = path.join(OUT_DIR, `${name}.js`);
    fs.writeFileSync(target, renderModule(name, data), 'utf8');
    written.push(path.relative(ROOT, target));
  }

  const indexPath = path.join(OUT_DIR, 'index.js');
  fs.writeFileSync(indexPath, renderIndex(names), 'utf8');
  written.push(path.relative(ROOT, indexPath));

  return written;
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const written = buildAll();
  console.log(`[build:sprites] wrote ${written.length} file(s):`);
  for (const file of written) console.log(`  ${file}`);
}
